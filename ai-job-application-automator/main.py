"""AI Job Application Automator.

For every job in data/jobs.json, uses Claude (Anthropic API) to compare it with
your resume and generate: a match score, skill gaps, a tailored cover letter and
a ready-to-send application email. Results go to output/.

Usage:
    python main.py                # uses Claude (needs ANTHROPIC_API_KEY)
    python main.py --dry-run      # offline keyword matching, no API key needed
"""
import argparse
import csv
import json
import os
import re
import sys
from pathlib import Path

MODEL = "claude-sonnet-5-5"
ROOT = Path(__file__).parent

PROMPT = """You are a career assistant. Compare the resume with the job description.
Reply with ONLY valid JSON using these keys:
  "match_score": integer 0-100,
  "matched_skills": list of strings,
  "missing_skills": list of strings,
  "cover_letter": string (max 200 words, specific to this job, no placeholders),
  "email_subject": string,
  "email_body": string (short, polite, mentions the attached resume).

RESUME:
{resume}

JOB:
Company: {company}
Role: {role}
Description: {description}
"""


def ask_claude(client, resume: str, job: dict) -> dict:
    msg = client.messages.create(
        model=MODEL,
        max_tokens=1500,
        messages=[{"role": "user", "content": PROMPT.format(resume=resume, **job)}],
    )
    text = msg.content[0].text
    return json.loads(text[text.index("{"): text.rindex("}") + 1])


def words(text: str) -> set:
    return set(re.findall(r"[a-z+#.]{2,}", text.lower()))


def offline_match(resume: str, job: dict) -> dict:
    """Keyword fallback so the pipeline runs without an API key."""
    r, j = words(resume), words(job["description"])
    common, missing = sorted(r & j), sorted(j - r)
    score = round(100 * len(common) / max(len(j), 1))
    return {
        "match_score": score,
        "matched_skills": common[:10],
        "missing_skills": missing[:10],
        "cover_letter": f"(dry-run) Cover letter for {job['role']} at {job['company']} would be generated by Claude.",
        "email_subject": f"Application for {job['role']}",
        "email_body": "(dry-run) Email body would be generated by Claude.",
    }


def save(out_dir: Path, job: dict, res: dict) -> None:
    slug = re.sub(r"\W+", "_", job["company"]).strip("_").lower()
    (out_dir / f"{slug}.md").write_text(
        f"# {job['role']} @ {job['company']}\n\n"
        f"**Match score:** {res['match_score']}/100\n\n"
        f"**Matched skills:** {', '.join(res['matched_skills'])}\n\n"
        f"**Missing skills:** {', '.join(res['missing_skills'])}\n\n"
        f"## Cover letter\n\n{res['cover_letter']}\n\n"
        f"## Email\n\n**Subject:** {res['email_subject']}\n\n{res['email_body']}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--resume", default=ROOT / "data" / "resume.txt", type=Path)
    ap.add_argument("--jobs", default=ROOT / "data" / "jobs.json", type=Path)
    ap.add_argument("--out", default=ROOT / "output", type=Path)
    ap.add_argument("--dry-run", action="store_true", help="skip the API, use keyword matching")
    args = ap.parse_args()

    resume = args.resume.read_text()
    jobs = json.loads(args.jobs.read_text())
    args.out.mkdir(exist_ok=True)

    client = None
    if not args.dry_run:
        if not os.getenv("ANTHROPIC_API_KEY"):
            print("ANTHROPIC_API_KEY not set. Add it to your environment or use --dry-run.")
            return 1
        import anthropic
        client = anthropic.Anthropic()

    rows = []
    for job in jobs:
        res = offline_match(resume, job) if args.dry_run else ask_claude(client, resume, job)
        save(args.out, job, res)
        rows.append([job["company"], job["role"], res["match_score"]])
        print(f"{job['company']:<12} {job['role']:<28} score={res['match_score']}")

    rows.sort(key=lambda r: r[2], reverse=True)
    with open(args.out / "summary.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["company", "role", "match_score"])
        w.writerows(rows)
    print(f"\nSaved {len(rows)} applications to {args.out}/ (ranked in summary.csv)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
